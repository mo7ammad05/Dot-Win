/**
 * 🇯🇴 محرك المرشد السياحي الذكي لمنصة Jordan Tour (Gemini AI Engine)
 * يتضمن الاتصال بالسحابة والنظام الموسوعي الذاتي المدمج لكافة معالم وتراث الأردن
 */

import { db } from '../config/firebase.config.js';

class GeminiService {
  constructor() {
    this.apiKey = '';
    localStorage.removeItem('jordan_gemini_api_key');
    this.candidateModels = ['gemini-2.5-flash', 'gemini-flash-latest', 'gemini-3.8-flash'];
    this.initCloudKeySync();
  }

  /**
   * الاستماع السحابي لمفتاح الـ API في حال تم تحديثه من لوحة الأدمن
   */
  initCloudKeySync() {
    if (!db) return;
    try {
      db.collection('settings').doc('ai_config').onSnapshot((doc) => {
        if (doc.exists && doc.data()?.apiKey) {
          this.apiKey = doc.data().apiKey.trim();
        }
      });
    } catch (e) {
      console.warn('AI cloud key sync notice:', e);
    }
  }

  /**
   * إرسال رسالة للمرشد الذكي وتلقي الرد المنسق
   * @param {string} userMessage 
   * @param {Array} history 
   * @returns {Promise<string>}
   */
  async askGuide(userMessage, history = []) {
    const cleanMsg = (userMessage || '').trim();
    if (!cleanMsg) return '';

    // 1. إذا وُجد مفتاح API متاح، نقوم بالاتصال المباشر بـ Google Gemini
    if (this.apiKey) {
      try {
        const reply = await this.callGeminiApi(cleanMsg, history);
        if (reply && reply.trim()) return reply.trim();
      } catch (err) {
        console.warn('Gemini API call failed, switching to local Jordan Travel Engine:', err.message);
      }
    }

    // 2. المحرك الموسوعي المحلي الذاتي الشامل (Zero-Failure Local Engine)
    return this.getLocalJordanReply(cleanMsg);
  }

  /**
   * استدعاء Google Gemini API مباشرة عبر REST API
   */
  async callGeminiApi(message, history) {
    const systemPrompt = `أنت "مرشد الأردن السياحي الذكي" 🇯🇴 لمنصة جولة في الأردن (Jordan Tour).

شخصيتك وأسلوبك:
أنت المرشد السياحي الأردني الأكثر وداً ودفئاً وترحيباً وحفاوة!
تتعامل مع السائل بروح النخوة والضيافة الأردنية الأصيلة وبكل مودة وابتسامة:
- ابدأ ردودك بترحيب ودود ومحبب: "يا هلا والله بضيف الأردن العزيز! 🌸"، "أهلاً وسهلاً بك، نورتنا ويسعدني جداً إفادتك ✨"، "على راسي تفضل هاي كل المعلومات بالتفصيل 🇯🇴".
- اختم ردودك دائماً بعبارة دافئة وتشجيعية: "أتمنى لك رحلة ممتعة وتجربة أردنية ساحرة! وأنا جاهز لأي سؤال ثاني ومن عيوني دائماً 🌿".
- استخدم الإيموجي المناسبة والجميلة لتكون الإجابة مبهجة ومنسقة.

نطاق الإجابة المفتوح والشامل:
1. كافة المحافظات الـ 12 ومدنها وقراها وباديتها (عمان، إربد، الزرقاء، المفرق، جرش، عجلون، البلقاء/السلط، مادبا، الكرك، الطفيلة، معان/البتراء/وادي رم/الشوبك، العقبة).
2. المعالم السياحية والأثرية والطبيعية ومسارات المشي والأودية.
3. التراث الشعبي والثقافة الأردنية الأصيلة وعادات القهوة السادة والدبكة.
4. المطبخ الأردني والأكلات الشعبية (المنسف، الزرب، المكمورة، الرشوف، الفتيت، قلاية البندورة، الكنافة).
5. تاريخ الأردن ورجالاته وملوكه وحضاراته من الأنباط حتى اليوم.
6. الخدمات واللوجستيات والسفر والدفع عبر كليك (CliQ: JORDANEXPLORER).`;

    const formattedContents = [];
    
    // ضبط صيغة المحادثة التناوبية لـ Gemini (User -> Model)
    for (const turn of history) {
      if (!turn.text || !turn.text.trim()) continue;
      const role = turn.sender === 'user' ? 'user' : 'model';
      if (formattedContents.length === 0 && role !== 'user') continue;

      if (formattedContents.length > 0 && formattedContents[formattedContents.length - 1].role === role) {
        formattedContents[formattedContents.length - 1].parts[0].text += `\n${turn.text}`;
      } else {
        formattedContents.push({ role, parts: [{ text: turn.text }] });
      }
    }

    formattedContents.push({ role: 'user', parts: [{ text: message }] });

    const payload = {
      contents: formattedContents,
      systemInstruction: { parts: [{ text: systemPrompt }] },
      generationConfig: { temperature: 0.6 }
    };

    let lastError = null;
    for (const model of this.candidateModels) {
      try {
        const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${encodeURIComponent(this.apiKey)}`;
        const res = await fetch(url, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(payload)
        });

        if (res.ok) {
          const data = await res.json();
          const answer = data.candidates?.[0]?.content?.parts?.[0]?.text;
          if (answer) return answer;
        }
      } catch (e) {
        lastError = e;
      }
    }

    throw lastError || new Error('No candidate model responded');
  }

  /**
   * النظام الموسوعي الذاتي لكافة معالم ومحافظات المملكة الأردنية الهاشمية
   * @param {string} query 
   * @returns {string}
   */
  getLocalJordanReply(query) {
    const q = query.toLowerCase();

    // 1. معان، البتراء، وادي رم، الشوبك
    if (q.includes('معان') || q.includes('بتراء') || q.includes('رم') || q.includes('شوبك')) {
      return `يا هلا والله بضيف الأردن العزيز! 🌸 مرحباً بك في درة الجنوب وعاصمة الأنباط:

• **محافظة معان والبتراء (إحدى عجائب الدنيا السبع)**:
  - **السيق والخزنة**: ممر صخري بطول 1.2 كم ينفتح على أعظم واجهة أثرية منحوتة بالصخر الوردي.
  - **الدير وجبل المذبح**: صرح أثري مهيب يتطلب صعود 800 درجة مع إطلالة تحبس الأنفاس على وادي عربة.
  - **البتراء ليلاً**: تجربة ساحرة تحت أضواء 1500 شمعة وأنغام الربابة البدوية.
• **صحراء وادي رم (وادي القمر)**:
  - سفاري سيارات 4x4 بين الكثبان الرملية الحمراء وأقواس الصخور الطبيعية.
  - التخييم الفلكي في قبب المريخ وتناول وجبة الزرب البدوي المدفونة تحت الرمال.
• **قلعة الشوبك (مونتريال)**: أقدم قلاع القرون الوسطى الشامخة فوق قمم جبال الشوبك.

💡 الحجز متاح ومؤكد فورياً عبر كليك (CliQ) مع ختم الجواز الرقمي الرسمي! 🇯🇴`;
    }

    // 2. الكرك ووادي الموجب
    if (q.includes('كرك') || q.includes('موجب') || q.includes('مؤتة')) {
      return `أهلاً وسهلاً بك في كرك الصمود والمجد! 🏰✨

• **قلعة الكرك التاريخية**: إحدى أضخم القلاع الصليبية والإسلامية، وتتميز بسراديبها وأنفاقها العميقة المكونة من سبعة طوابق وأبراجها المطلة على البحر الميت.
• **محمية وادي الموجب للمحيط الحيوي**: أعمق وادٍ مائي في الشرق الأوسط، يتيح أروع مغامرة سباحة وإنزال مائي بين الشلالات الطبيعية.
• **المزار الجنوبي**: مقامات شهداء معركة مؤتة الأجلاء (جعفر الطيار، زيد بن حارثة، وعبد الله بن رواحة).
• **أكلات الكرك الشهيرة**: موطن المنسف الأردني الأصيل بالجميد الكركي البلدي، والرشوف بالسمن البلقاوي.`;
    }

    // 3. عجلون وجرش
    if (q.includes('جرش') || q.includes('عجلون') || q.includes('تلفريك') || q.includes('ربض')) {
      return `يا هلا بريحة الشمال وغابات الأردن الخضراء! 🌿🏛️

• **مدينة جرش الأثرية (بومبي الشرق)**:
  - الساحة البيضاوية الفريدة المحاطة بـ 56 عموداً أيونياً.
  - شارع الأعمدة (الكاردو) المرصوف بحجارة ما زالت تحتفظ بآثار عجلات العربات الرومانية.
  - المسرح الجنوبي ذو الهندسة الصوتية الخارقة ومعبد أرتميس.
• **محافظة عجلون الخلابة**:
  - قلعة عجلون (قلعة الربض) المشيدة عام 1184م بأمر صلاح الدين الأيوبي.
  - **تلفريك عجلون السياحي**: رحلة هوائية ممتعة بطول 2.5 كم فوق أحضان غابات السنديان والبلوط.
  - زيت الزيتون البكر الممتاز ودبس الرمان والتين البلدي.`;
    }

    // 4. البحر الميت وماعين
    if (q.includes('بحر ميت') || q.includes('ماعين') || q.includes('طفو') || q.includes('طين')) {
      return `أهلاً وسهلاً بك في أخفض بقعة على وجه الأرض! 🌊💆‍♂️

• **البحر الميت (430 متراً تحت سطح البحر)**:
  - تجربة الطفو الطبيعي بلا أي جهد في أملح مياه العالم الغنية بأكثر من 21 معدناً علاجياً.
  - أقنعة الطين الأسود الطبيعي لتجديد البشرة والاسترخاء التام.
  - غروب شمس ذهبي ساحر فوق التلال والجبال الأردنية.
• **حمامات ماعين المعدنية الحارة**:
  - شلالات مياه كبريتية دافئة تتدفق من جوف الأرض للاستشفاء الطبيعي وتسكين العضلات.`;
    }

    // 5. السلط ومادبا
    if (q.includes('سلط') || q.includes('مادبا') || q.includes('فسيفساء') || q.includes('نيبو') || q.includes('بلقاء')) {
      return `على راسي والله، مرحباً بك في مدن التراث العالمي والفسيفساء! 🕌⛪

• **مدينة السلط (مدرجة في اليونسكو للتراث العالمي)**:
  - بيوت الحجر الأصفر العريقة ذات الشبابيك الثلاثية المعمارية المتناغمة.
  - شارع الحمام التراثي ومسار الوئام الديني وروح التسامح والضيافة الأردنية الأصيلة.
• **محافظة مادبا وجبل نيبو**:
  - أقدم خارطة فسيفسائية مرسومة للقدس والأراضي المقدسة في كنيسة القديس جورج (القرن السادس الميلادي).
  - جبل نيبو المقدس ومطل وادي الأردن والبحر الميت.`;
    }

    // 6. العقبة والبحر الأحمر
    if (q.includes('عقبة') || q.includes('غوص') || q.includes('مرجان') || q.includes('سمك') || q.includes('صيادية')) {
      return `يا مية هلا بثغر الأردن الباسم وبوابة البحر الأحمر! 🐠⛵

• **خليج العقبة ومحمية المرجان**:
  - مياه دافئة مشمسة على مدار العام، وأندر الحدائق المرجانية في العالم.
  - مواقع غوص عالمية تشمل السفينة العسكرية الغارقة (سيدار برايد) والدبابة والطائرة العسكرية.
  - رحلات اليخوت والزوارق الزجاجية والاسترخاء في تالا بيه وأيلة.
  - وليمة الصيادية العقباوية بالسمك الطازج والبهارات الخاصة.`;
    }

    // 7. الطعام والمطبخ الأردني
    if (q.includes('أكل') || q.includes('طعام') || q.includes('منسف') || q.includes('زرب') || q.includes('كنافة')) {
      return `صحتين وهنا مقدماً! المطبخ الأردني رمز الكرم والنخوة 🇯🇴🍽️:

1. **المنسف الأردني (المدرج في اليونسكو)**: لحم بلدي مطبوخ بالجميد الكركي الأصيل، يُقدم فوق أرز أصفر وخبز الشراك الرقيق ويزين باللوز والصنوبر المقلي مع السمن البلدي.
2. **الزرب البدوي**: لحم ودجاج وخضار يُطهى ببطء لساعات في براميل محكمة تحت رمال وصخور وادي رم الملتهبة بنكهة الحطب.
3. **المكمورة الإربدية**: طبقات متناغمة من العجين البلدي المحشو بالدجاج والبصل وزيت الزيتون الشمالي الفاخر.
4. **الكنافة النابلسية الساخنة وقلاية البندورة باللحمة البلدية** مع شاي الميرمية على الحطب.`;
    }

    // 8. الدفع عبر CliQ
    if (q.includes('كليك') || q.includes('cliq') || q.includes('دفع') || q.includes('حجز')) {
      return `خطوات الدفع الفوري والمؤكد عبر نظام كليك (CliQ) في الأردن 🇯🇴💳:

1. افتح تطبيق بنكك الأردني واختر خدمة التحويل عبر كليك (CliQ).
2. استخدم الاسم المستعار الرسمي المعتمد للمنصة: **JORDANEXPLORER**.
3. أرسل قيمة الحجز وسيقوم النظام فوراً بتوليد تذكرتك برمز QR وتفعيل الختم في جواز سفرك الرقمي!`;
    }

    // الرد العام الدافئ والترحيبي
    return `يا هلا والله بضيف الأردن العزيز! 🌸🇯🇴 يسعدني جداً مساعدتك وإرشادك في كل ما تحتاجه عن مملكتنا الحبيبة:

• **المحافظات الـ 12**: (معان والبتراء، وادي رم، العقبة، الكرك، الطفيلة وضانا، مادبا، السلط، العاصمة عمان، الزرقاء، المفرق، جرش، عجلون، وإربد).
• **الأنشطة**: برامج الرحلات، حجز التذاكر، الدفع بكليك (JORDANEXPLORER)، وجمع الأختام التراثية الـ 12.
• **المأكولات**: المنسف، الزرب، والمطاعم الأصيلة.

تفضل بسؤالي عن أي معلم أو تفصيل وسأجيبك بكل سرور وعيوني لك دائماً! ✨🌿`;
  }
}

export const geminiService = new GeminiService();